/** 日付で決まる行事。学校ごとに日が違うものは幅を持たせ、台詞もぼかす（「近い人もいるかな」） */
export type GreetingEvent =
  | 'newYear' | 'winterAfter' | 'kyotsuTest' | 'setsubun' | 'yearEnd' | 'springBreak' | 'newTerm' | 'goldenWeek'
  | 'examSeason' | 'tanabata' | 'summerBefore' | 'summerBreak' | 'summerAfter' | 'winterBefore' | 'winterBreak';

/** 小テスト（quiz_ranges.due_date）から決まる場面 */
export type QuizMoment = 'quizToday' | 'quizSoon';

export type TeacherGreetings = {
  /** 月ごとのあいさつ。添字 0 = 1月 … 11 = 12月 */
  month: string[][];
  events: Record<GreetingEvent | QuizMoment, string[]>;
};

/** [開始の月, 日, 終わりの月, 日]（両端を含む）。年をまたぐ幅は使わない */
type Window = readonly [number, number, number, number];

