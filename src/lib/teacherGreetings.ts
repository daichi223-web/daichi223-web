const GREETING_EVENTS = Object.keys(EVENT_WINDOWS) as GreetingEvent[];

const inWindow = (m: number, d: number, [m1, d1, m2, d2]: Window): boolean => {
  const v = m * 100 + d;
  return v >= m1 * 100 + d1 && v <= m2 * 100 + d2;
};

/** その日にあたる行事（複数あれば全部） */
export function eventsOn(date: Date): GreetingEvent[] {
  const m = date.getMonth() + 1;
  const d = date.getDate();
  return GREETING_EVENTS.filter((e) => EVENT_WINDOWS[e].some((w) => inWindow(m, d, w)));
}

