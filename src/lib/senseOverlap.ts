const key = (a: string, b: string) => (a < b ? `${a}|${b}` : `${b}|${a}`);
const OVERLAP = new Set(SENSE_OVERLAP_PAIRS.map(([a, b]) => key(a, b)));

/** 2つの意味（qid）が、選択肢に一緒に出さない組か */
export function isOverlapPair(a: string, b: string): boolean {
  return a !== b && OVERLAP.has(key(a, b));
}
