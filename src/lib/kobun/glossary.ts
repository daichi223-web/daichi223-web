const BY_TERM = new Map(GLOSSARY.map((g) => [g.term, g]));
// 長い語を先に試す（「形容動詞」を「動詞」より、「格助詞」を「助詞」より先に）
const PATTERN = new RegExp(
  `(${[...BY_TERM.keys()].sort((a, b) => b.length - a.length).join("|")})`
);

export type GlossPart = { text: string; entry?: GlossEntry };

/**
 * 文を用語とそれ以外に分ける。用語は1つの文につき最初の1回だけ印を付ける
 * （同じ語に何度も印があると読みにくい）。exclude はそのカード自身の見出し語など。
 */
export function splitGloss(text: string, exclude: string[] = []): GlossPart[] {
  const seen = new Set(exclude);
  const out: GlossPart[] = [];
  for (const piece of text.split(PATTERN)) {
    if (!piece) continue;
    const entry = BY_TERM.get(piece);
    if (entry && !seen.has(piece)) {
      seen.add(piece);
      out.push({ text: piece, entry });
    } else if (out.length && !out[out.length - 1].entry) {
      out[out.length - 1].text += piece;
    } else {
      out.push({ text: piece });
    }
  }
  return out;
}
