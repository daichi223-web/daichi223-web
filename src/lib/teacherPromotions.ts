/**
 * 今回新しく記録された段（recordPromotion の戻り値）から、祝う段を決める。
 * はじめての記録（第1階を含む＝この端末で初めて）は祝わない。何段か一気に上がったときは一番上の段。
 */
export function celebrationFrom(added: readonly { n: number; rank: string }[]): { n: number; rank: string } | null {
  if (added.length === 0 || added.some((r) => r.n === 1)) return null;
  const top = added.reduce((a, b) => (b.n > a.n ? b : a));
  return { n: top.n, rank: top.rank };
}

/** 昇進のお祝いの一言。台詞の無い先生は null */
export function pickPromotion({ teacher, n, rank, seed = '' }: { teacher: TeacherId; n: number; rank: string; seed?: string }): string | null {
  const lines = TEACHER_PROMOTIONS[teacher]?.[promotionKeyFor(n)];
  if (!lines || lines.length === 0) return null;
  return pickVariant(lines, `promo:${teacher}:${n}:${seed}`).replace(/\{位\}/g, rankFullName(rank));
}
