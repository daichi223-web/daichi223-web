export type PromotionKey = 'jige' | 'tenjoFirst' | 'tenjo' | 'kugyoFirst' | 'kugyo' | 'kyokui';
export const PROMOTION_KEYS: readonly PromotionKey[] = ['jige', 'tenjoFirst', 'tenjo', 'kugyoFirst', 'kugyo', 'kyokui'];

/** 第 n 階に上がったときの台詞の種類 */
export function promotionKeyFor(n: number): PromotionKey {
  if (n >= 21) return 'kyokui';
  if (n === 16) return 'kugyoFirst';
  if (n >= 17) return 'kugyo';
  if (n === 8) return 'tenjoFirst';
  if (n >= 9) return 'tenjo';
  return 'jige';
}

/** 位の略記を読める形に：「従五下」→「従五位下」、「正一」→「正一位」。無位・八位・七位はそのまま */
export function rankFullName(rank: string): string {
  const m = /^(従|正)([一二三四五六七八九])(上|下)?$/.exec(rank);
  return m ? `${m[1]}${m[2]}位${m[3] ?? ''}` : rank;
}

