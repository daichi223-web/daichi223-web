// === 解決テーブルを構築 ===
// alias key → vocabIndex に実在する正規 key
const ALIAS_TO_VOCAB_KEY: Record<string, string> = {};

// 1. 「・」分割エイリアス (例: "のたまふ・のたまはす" → "のたまふ" / "のたまはす" 両方が link)
for (const key of vocabKeys) {
  if (!key.includes('・')) continue;
  for (const part of key.split('・')) {
    const p = part.trim();
    if (!p || p.includes('～')) continue; // 「ゆめゆめ～打消・禁止」等を除外
    if (vocabKeys.has(p)) continue;
    if (!ALIAS_TO_VOCAB_KEY[p]) ALIAS_TO_VOCAB_KEY[p] = key;
  }
}

// 2. 派生形・連用形などの個別 alias
for (const [from, to] of Object.entries(DERIVATIVE_TO_LEMMA)) {
  if (vocabKeys.has(to) && !ALIAS_TO_VOCAB_KEY[from]) ALIAS_TO_VOCAB_KEY[from] = to;
}
for (const [from, to] of Object.entries(INFLECTION_ALIAS)) {
  if (vocabKeys.has(to) && !ALIAS_TO_VOCAB_KEY[from]) ALIAS_TO_VOCAB_KEY[from] = to;
}

// 3. 漢字表記 → hiragana lemma
for (const [lemma, variants] of Object.entries(KANJI_VARIANTS)) {
  if (!vocabKeys.has(lemma)) continue;
  for (const v of variants) {
    if (vocabKeys.has(v)) continue;
    if (!ALIAS_TO_VOCAB_KEY[v]) ALIAS_TO_VOCAB_KEY[v] = lemma;
  }
}

/**
 * 単語帳の見出しと同音だが別の語の基本形（2026-10-25）。教材データの baseForm にこれが入っていれば紐づけない。
 *   触る（さはる＝触れる）：単語帳の「さはる」は「障る」（妨げられる）。基本形は scripts/fix-affix-pos.cjs が hint から入れる
 */
const OTHER_WORD_BASE = new Set<string>(['触る']);

/**
 * 1語にまとめた複合語・派生語 → 単語帳の構成語の見出し（2026-10-25）。
 * 正本の品詞分解の表は複合語を（複）（接頭）で1行にしている。品詞・活用は末尾の語のものなので、
 * 品詞の照合をせずに、学ぶ中心の語（hint が説明している語）の見出しへ送る。基本形か表層形で引く。
 * 「うち泣く」は入れない（単語帳の「うち」は名詞＝宮中・中で、接頭語ではない）。
 */
const COMPOUND_TO_LEMMA: Record<string, string> = {
  'うちまもる': 'まもる',         // 若紫の君「うちまもりて」
  '聞こえやる': 'きこゆ',         // 飽かぬ別れ「聞こえやらず」
  '聞こえまほしげなり': 'きこゆ', // 飽かぬ別れ「聞こえまほしげなること」
  '帰り参る': 'まゐる',           // 飽かぬ別れ「帰り参りぬ」
  '念じあふ': 'ねんず',           // 母子の別離「念じあへず」
  '群れゐる': 'ゐる',             // 東下り（都鳥）「群れゐて」
  '女はらから': 'はらから',       // 初冠「女はらから」（姉妹）
  'おぼつかなさ': 'おぼつかなし', // 猟師、仏を射ること（形容詞の名詞形）
};

/**
 * トークンの表層形 (text) と基本形 (baseForm) から、対応する vocabIndex の正規 key を解決する。
 * - vocabIndex に直接ある場合はそれを返す
 * - エイリアス経由で解決できる場合はその先の key を返す
 * - 該当なしなら null
 */
export function resolveVocabKey(
  text: string,
  baseForm: string | undefined | null,
  pos?: string | null,
  tag?: { conjugationType?: string | null; honorific?: string | null } | null,
): string | null {
  const base = (baseForm ?? '').trim();
  // 基本形が単語帳の同音語と別の語だと分かっているときは紐づけない（表層形の一致でも拾わない）
  if (base && OTHER_WORD_BASE.has(base)) return null;
  const t = (text ?? '').trim().replace(/^[、。「」『』（）\s]+|[、。「」『』（）\s]+$/g, '');
  const comp = (base && COMPOUND_TO_LEMMA[base]) || (t && COMPOUND_TO_LEMMA[t]) || null;
  if (comp && vocabKeys.has(comp)) {
    return comp === 'きこゆ' && tag?.honorific === '謙譲' && vocabKeys.has('きこゆ・きこえさす') ? 'きこゆ・きこえさす' : comp;
  }
  const cands = [
    base && vocabKeys.has(base) ? base : null,
    t && vocabKeys.has(t) ? t : null,
    base ? ALIAS_TO_VOCAB_KEY[base] : null,
    t ? ALIAS_TO_VOCAB_KEY[t] : null,
  ];
  for (const k0 of cands) {
    if (!k0 || !posCompatible(k0, pos)) continue;
    // 謙譲の「聞こゆ」は「きこゆ・きこえさす」（申し上げる）の見出しへ
    const k = k0 === 'きこゆ' && tag?.honorific === '謙譲' && vocabKeys.has('きこゆ・きこえさす') ? 'きこゆ・きこえさす' : k0;
    if (!conjCompatible(k, pos, tag?.conjugationType)) continue;
    return k;
  }
  // 表層形が別の品詞の見出しと同じ形で、上の照合で落ちる語（2026-10-25）
  const redirect = SAME_FORM_OTHER_POS[`${t}|${(pos ?? '').trim()}`];
  if (redirect && vocabKeys.has(redirect)) return redirect;
  return null;
}

/**
 * 表層形が単語帳の別の品詞の見出しと同じ形なので、品詞の照合で落ちてしまう語の行き先（`表層形|品詞` → 見出し）。
 *   おぼえ（動詞「覚ゆ」の連用形）：見出し「おぼえ」は名詞（評判）なので、動詞は「おぼゆ」へ
 *   とく（形容詞「疾し」の連用形）：単語帳の副詞「とく」（早く）と同じ語（「いたく」と同じ扱い）
 */
const SAME_FORM_OTHER_POS: Record<string, string> = {
  'おぼえ|動詞': 'おぼゆ',
  'おぼえ|補助動詞': 'おぼゆ',
  'とく|形容詞': 'とく',
};

/**
 * 同音の別の動詞に紐づくのを、活用の種類で防ぐ（2026-10-23）。
 * 単語帳の見出しの活用の種類と食い違うときは紐づけない。活用の種類が無いトークンは従来どおり通す。
 *   さる（避る＝ラ四）：ラ変「さる」（然り）は別語
 *   おくる（後る＝ラ下二）：ラ四「送る・贈る」は別語
 *   あふ（会ふ＝ハ四）：ハ下二「敢ふ」は別語。補助動詞「〜あふ」も紐づけない
 *   あく（飽く＝カ四・カ上二）：カ下二「明く・開く」は別語
 *   かく（斯く＝副詞）・とく（疾く＝副詞）：動詞「掛く・書く・解く」は別語
 */
const CONJ_ALLOWED: Record<string, RegExp> = {
  'さる': /^ラ四/,
  'おくる': /^ラ下二/,
  'あふ': /^ハ四/,
  'あく': /^カ(四|上二)/,
  // おこす（遣す＝よこす、サ下二）：サ四「起こす」（火をおこす）は別語（2026-10-25）
  'おこす': /^サ下二/,
};
const ADVERB_ONLY = new Set(['かく', 'とく']);
function conjCompatible(vocabKey: string, pos?: string | null, conjugationType?: string | null): boolean {
  const p = (pos ?? '').trim();
  if (ADVERB_ONLY.has(vocabKey) && (p === '動詞' || p === '補助動詞')) return false;
  if (vocabKey === 'あふ' && p === '補助動詞') return false;
  const re = CONJ_ALLOWED[vocabKey];
  const ct = (conjugationType ?? '').trim();
  if (!re || !ct) return true;
  return re.test(ct);
}

/**
 * 品詞の食い違いで同形の別語に紐づくのを防ぐ（2026-10-16）。
 * 例：接尾語「さ」「たち」、感動詞「あはれ」、連体詞「さる」が、副詞「さ」・動詞「たつ」・形容動詞「あはれなり」・動詞「避る」に当たっていた。
 * 品詞分解に品詞が無い語（多くの名詞）は従来どおり通す。
 */
const vocabPosOf = bundledVocabIndex as Record<string, { pos?: string }>;
// 単語帳（クイズ）の側の品詞。vocabIndex の pos が古い・粗い見出しがある（はべり＝「はべるの連用形／別表記」、かく＝「動詞（3系統）」、
// さ＝「接頭辞」、ことなり＝「名詞」）。そのせいで はべり 165・副詞かく 96・副詞さ 42 などが紐づいていなかったので、クイズのデータの品詞も見る（2026-10-25）
const quizPosOf: Record<string, string> = {};
for (const q of bundledKobunQ as { lemma?: string; pos?: string }[]) {
  if (q.lemma && q.pos && !(quizPosOf[q.lemma] ?? '').includes(q.pos)) quizPosOf[q.lemma] = `${quizPosOf[q.lemma] ?? ''} ${q.pos}`;
}
const FAMILY: Record<string, string> = {
  動詞: '動詞', 補助動詞: '動詞', 形容詞: '形容詞', 形容動詞: '形容動詞', 副詞: '副詞',
  名詞: '名詞', 代名詞: '名詞', 感動詞: '感動詞', 連体詞: '連体詞', 接続詞: '接続詞',
};
function posCompatible(vocabKey: string, pos?: string | null): boolean {
  const p = (pos ?? '').trim();
  if (!p) return true;
  if (p === '接尾語' || p === '接頭語' || p === '記号') return false;
  const fam = FAMILY[p];
  if (!fam) return true;
  const vp = `${vocabPosOf[vocabKey]?.pos ?? ''} ${quizPosOf[vocabKey] ?? ''}`.trim().replace(/形容動詞/g, 'ケイヨウドウシ');
  if (!vp || vp.includes('連語')) return true;
  const want = fam === '形容動詞' ? 'ケイヨウドウシ' : fam;
  return vp.includes(want);
}

