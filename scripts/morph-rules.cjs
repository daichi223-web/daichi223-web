/**
 * 古文の接続規則。「次に来る語」から、いま見ている語の活用形を絞る。
 *
 * 使い方
 *   const { allowedForms } = require('./morph-rules.cjs');
 *   allowedForms('けり')  // → Set { '用' }
 *
 * 返すのは「ありうる活用形の集合」。決められないものは null を返す。
 * 辞書の候補を絞るためだけに使い、ここから新しいラベルを作ることはしない。
 *
 * 表記: 未=未然 用=連用 終=終止 体=連体 已=已然 命=命令
 */

/**
 * 次の語 → ありうる活用形
 *
 * 表は正本（既存108教材の品詞分解）と突き合わせて確かめてある。
 * **絞り込みにしか使わない**ので、迷ったら広く取る（正解を落とすほうが害が大きい）。
 * 同じ仮名に別語がある場合は両方を入れてある。理由をその場に書く。
 */
const NEXT_TO_FORMS = {
  // --- 未然形に付くもの ---
  ず: ['未'], ざり: ['未'], ざる: ['未'], ざれ: ['未'], ざら: ['未'],
  じ: ['未'], む: ['未'], ん: ['未'], むず: ['未'], んず: ['未'],
  まほし: ['未'], まほしく: ['未'],
  らる: ['未'], られ: ['未'], らるる: ['未'],
  さす: ['未'], させ: ['未'], しむ: ['未'], しめ: ['未'],
  で: ['未'],
  // まし＝未然接続だが、連用形の下に来る例が正本にある
  まし: ['未', '用'], ましか: ['未', '用'],

  // --- 連用形に付くもの ---
  き: ['用'], しか: ['用'],
  けり: ['用'], ける: ['用'], けれ: ['用'], けら: ['用'],
  つ: ['用'], て: ['用'], つる: ['用'], つれ: ['用'], てよ: ['用'],
  たり: ['用'], たら: ['用'], たる: ['用'], たれ: ['用'],
  けむ: ['用'], けん: ['用'],
  たし: ['用'], たく: ['用'],
  つつ: ['用'],
  // ながら＝連用形接続／体言・連体形にも付く（「ありしながら」「昔ながら」）
  ながら: ['用', '体'],
  // し＝過去「き」連体形（連用接続）／副助詞・サ変未然など
  し: ['用', '未'],
  // ぬ＝完了（連用接続）／打消「ず」連体形（未然接続）
  ぬ: ['用', '未'],
  // ね＝打消「ず」已然形（未然接続）／完了「ぬ」命令形（連用接続）
  ね: ['未', '用'],
  // に＝完了「ぬ」連用形（連用接続）／断定・格助詞（体言・連体）
  に: ['用', '体'],
  // る・れ＝受身尊敬（未然接続）／完了「り」（サ変未然・四段命令）
  る: ['未', '命', '已'], れ: ['未', '命', '已'], るる: ['未'],
  す: ['未'], せ: ['未'],

  // --- 終止形に付くもの（ラ変型には連体形が付くので体も許す） ---
  べし: ['終', '体'], べき: ['終', '体'], べく: ['終', '体'],
  べから: ['終', '体'], べけれ: ['終', '体'],
  らし: ['終', '体'], らむ: ['終', '体'], らん: ['終', '体'],
  めり: ['終', '体'], まじ: ['終', '体'], まじき: ['終', '体'],
  とも: ['終', '体'],

  // --- 連体形・体言に付くもの ---
  ごとし: ['体'], ごとく: ['体'],
  が: ['体'],
  // を＝格助詞（体言・連体）／間投助詞（連用形の下にも来る「のどかにを」）
  を: ['体', '用'],
  // ぞ＝係助詞（連体で結ぶ）／文末の念押し（終止形の下）
  ぞ: ['体', '終'],
  // 係助詞は連用形の下にも来る（「〜ては」「〜ても」）
  は: ['体', '用'], も: ['体', '用', '終'],
  // なむ＝願望の終助詞（未然）／強意「な」＋推量「む」（連用）／係助詞（体言・連体）
  なむ: ['未', '用', '体'],

  // --- 已然形に付くもの ---
  ど: ['已'], ども: ['已'],

  // --- どちらもありうるもの ---
  ば: ['未', '已'],           // 順仮（未）／順確（已）
  // なり＝伝聞推定（終・ラ変型は体）／断定（体言・連体）／動詞「成る」（連用の下）
  なり: ['終', '体', '用'], なる: ['終', '体', '用'], なれ: ['終', '体', '用'],
};

/** 文末（。や 」）に来る語の活用形 */
const SENTENCE_END = ['終', '命', '体', '已'];

/** 次の語から、ありうる活用形の集合を返す。決められないときは null */
function allowedForms(nextWord) {
  if (nextWord === undefined || nextWord === null) return null;
  const w = String(nextWord).trim();
  if (w === '') return null;
  if (/^[。．.]$/.test(w)) return new Set(SENTENCE_END);
  const hit = NEXT_TO_FORMS[w];
  return hit ? new Set(hit) : null;
}

/** ラベル（「サ四・未」「過去・体（結）」など）から活用形を取り出す。無ければ null */
function formOf(label) {
  if (!label) return null;
  for (const seg of String(label).split('・')) {
    const m = seg.match(/^([未用終体已命])(?:[（(].*)?$/);
    if (m) return m[1];
  }
  return null;
}

module.exports = { allowedForms, formOf, NEXT_TO_FORMS };
