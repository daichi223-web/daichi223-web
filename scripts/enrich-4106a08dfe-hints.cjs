function keyOf(tk) {
  const g = tk.grammarTag || {};
  return `${tk.text}|${g.pos || ''}|${g.meaning || ''}`;
}

let added = 0;
for (const s of t.sentences) {
  for (const tk of s.tokens) {
    if (tk.hint) continue;
    let h = pinpoint[tk.id];
    if (!h) h = byKey[keyOf(tk)];
    if (!h) {
      // 「世」「もの」等は pos 無し・meaning 無しなので text だけで引く
      h = byKey[`${tk.text}|||`];
    }
    if (h) { tk.hint = h; added++; }
  }
}

