const FORM = { '未': '未然形', '用': '連用形', '終': '終止形', '体': '連体形', '已': '已然形', '命': '命令形' };

function fallback(tk) {
  const g = tk.grammarTag || {};
  const pos = g.pos || '';
  if (!['動詞', '形容詞', '形容動詞', '補助動詞'].includes(pos)) return null;
  const type = g.conjugationType ? `(${g.conjugationType})` : '';
  const form = FORM[g.conjugationForm] || '';
  if (!form) return null;
  const head = g.baseForm ? `${pos}「${g.baseForm}」${type}の${form}「${tk.text}」` : `${pos}${type}の${form}「${tk.text}」`;
  return head;
}

function keyOf(tk) {
  const g = tk.grammarTag || {};
  return `${tk.text}|${g.pos || ''}|${g.meaning || ''}`;
}

function applyHints(id, pinpoint, extraByKey = {}, extraNounKey = {}) {
  const fp = path.join(__dirname, '..', 'public', 'texts-v3', `${id}.json`);
  const distFp = path.join(__dirname, '..', 'dist', 'texts-v3', `${id}.json`);
  const t = JSON.parse(fs.readFileSync(fp, 'utf8'));
  const bk = { ...byKey, ...extraByKey };
  const nk = { ...nounKey, ...extraNounKey };
  const skip = new Set(['、', '。', '「', '」', '・']);
  let added = 0, fb = 0;
  for (const s of t.sentences) {
    for (const tk of s.tokens) {
      if (tk.hint || skip.has(tk.text)) continue;
      const g = tk.grammarTag || {};
      let h = pinpoint[tk.id] || bk[keyOf(tk)] || bk[`${tk.text}|${g.pos || ''}|`] || nk[tk.text];
      if (!h) { h = fallback(tk); if (h) fb++; }
      if (h) { tk.hint = h; added++; }
    }
  }
  let ok = true;
  for (const s of t.sentences) if (s.tokens.map((tk) => tk.text).join('') !== s.originalText) ok = false;
  if (!ok) { console.error('alignment NG: 書き込まない'); process.exit(1); }
  fs.writeFileSync(fp, JSON.stringify(t, null, 2), 'utf8');
  if (fs.existsSync(path.dirname(distFp))) fs.writeFileSync(distFp, JSON.stringify(t, null, 2), 'utf8');
  const all = t.sentences.flatMap((s) => s.tokens);
  const meaningful = all.filter((tk) => (tk.layer && tk.layer > 0) || (tk.grammarTag && tk.grammarTag.pos));
  const mh = meaningful.filter((tk) => tk.hint).length;
  const total = all.filter((tk) => tk.hint).length;
  console.log('Hints added:', added, '(予備の説明', fb, ')');
  console.log('Total:', total + '/' + all.length, Math.round(total / all.length * 100) + '%');
  console.log('Meaningful:', mh + '/' + meaningful.length, Math.round(mh / meaningful.length * 100) + '%');
  console.log('alignment ok:', ok);
  for (const s of t.sentences) for (const tk of s.tokens) {
    if (!tk.hint && ((tk.layer && tk.layer > 0) || (tk.grammarTag && tk.grammarTag.pos))) console.log('残:', tk.id, tk.text, (tk.grammarTag || {}).pos);
  }
  return Math.round(total / all.length * 100);
}

module.exports = { byKey, nounKey, applyHints };
